"""Provenance rules: generation cycles and the design-build-test-learn role conventions for Activities,
Associations, and Usages."""

from __future__ import annotations

from typing import Dict, List

from sbol_utilities.validation.catalog import Context
from sbol_utilities.validation.sbol2 import REGISTRY
from sbol_utilities.validation.sbol2 import spec as S
from sbol_utilities.validation.sbol2.context import Sbol2Context, nodes_reaching_cycles


@REGISTRY.rule("sbol2-10223")
def generation_cycles(context: Context) -> None:
    """wasGeneratedBy and the entities of the generating Activities' Usages do not form a cycle."""
    ctx: Sbol2Context = context  # type: ignore[assignment]
    graph: Dict[str, List[str]] = {}
    starts = []
    for obj in ctx.objects:
        if obj.iri is None:
            continue
        starts.append(obj.iri)
        successors = []
        for activity in ctx.children(obj, S.WAS_GENERATED_BY):
            for usage in ctx.children(activity, S.QUALIFIED_USAGE):
                entity = usage.first_ref(S.ENTITY)
                if entity is not None:
                    successors.append(entity)
        if successors:
            graph[obj.iri] = successors
    if not graph:
        return
    offenders = nodes_reaching_cycles(graph, starts)
    for obj in ctx.objects:
        if obj.iri in offenders:
            ctx.error(
                "sbol2-10223",
                obj,
                "provenance formed by wasGeneratedBy and Usage entity references must not be circular",
                S.WAS_GENERATED_BY,
            )


@REGISTRY.rule("sbol2-10224", "sbol2-10225", "sbol2-10226", "sbol2-10227")
def generated_object_kinds(context: Context) -> None:
    """An object generated by a design/build/test/learn Activity has the matching TopLevel kind."""
    ctx: Sbol2Context = context  # type: ignore[assignment]
    if not ctx.config.best_practice:
        return
    for obj in ctx.sbol_objects:
        is_implementation = obj.has_class(S.IMPLEMENTATION)
        is_experimental_data = obj.has_class(S.EXPERIMENTAL_DATA)
        for activity in ctx.children(obj, S.WAS_GENERATED_BY):
            for association in ctx.children(activity, S.QUALIFIED_ASSOCIATION):
                for role in association.iris(S.HAD_ROLE):
                    if role == S.ROLE_DESIGN and (is_implementation or not obj.is_top_level):
                        ctx.error(
                            "sbol2-10224",
                            obj,
                            "an object generated by a design Activity SHOULD be a TopLevel other than Implementation",
                        )
                    elif role == S.ROLE_BUILD and not is_implementation:
                        ctx.error(
                            "sbol2-10225", obj, "an object generated by a build Activity SHOULD be an Implementation"
                        )
                    elif role == S.ROLE_TEST and not is_experimental_data:
                        ctx.error(
                            "sbol2-10226", obj, "an object generated by a test Activity SHOULD be ExperimentalData"
                        )
                    elif role == S.ROLE_LEARN and is_implementation:
                        ctx.error(
                            "sbol2-10227",
                            obj,
                            "an object generated by a learn Activity SHOULD NOT be an Implementation",
                        )


_ACTIVITY_CONFLICTS = (
    (S.ROLE_DESIGN, "sbol2-12408", (S.ROLE_BUILD, S.ROLE_TEST)),
    (S.ROLE_BUILD, "sbol2-12409", (S.ROLE_TEST, S.ROLE_LEARN)),
    (S.ROLE_TEST, "sbol2-12410", (S.ROLE_DESIGN, S.ROLE_LEARN)),
    (S.ROLE_LEARN, "sbol2-12411", (S.ROLE_DESIGN, S.ROLE_BUILD)),
)


@REGISTRY.rule("sbol2-12408", "sbol2-12409", "sbol2-12410", "sbol2-12411")
def activity_usage_roles(context: Context) -> None:
    """An Activity's Usage roles do not conflict with the role of its Association."""
    ctx: Sbol2Context = context  # type: ignore[assignment]
    if not ctx.config.best_practice:
        return
    for obj in ctx.sbol_objects:
        if not obj.has_class(S.ACTIVITY):
            continue
        association_roles = {r for a in ctx.children(obj, S.QUALIFIED_ASSOCIATION) for r in a.iris(S.HAD_ROLE)}
        usage_roles = {r for u in ctx.children(obj, S.QUALIFIED_USAGE) for r in u.iris(S.HAD_ROLE)}
        for association_role, rule, forbidden in _ACTIVITY_CONFLICTS:
            if association_role in association_roles and any(r in usage_roles for r in forbidden):
                ctx.warning(
                    rule,
                    obj,
                    "an Activity's Usage roles should not conflict with its Association role",
                    S.QUALIFIED_USAGE,
                )


@REGISTRY.rule("sbol2-12504", "sbol2-12505", "sbol2-12506", "sbol2-12507")
def usage_entity_kinds(context: Context) -> None:
    """A Usage with a design/build/test/learn role refers to an entity of the kind that role expects."""
    ctx: Sbol2Context = context  # type: ignore[assignment]
    if not ctx.config.best_practice:
        return
    for obj in ctx.sbol_objects:
        if not obj.has_class(S.USAGE):
            continue
        entity = ctx.resolve(obj.first_ref(S.ENTITY))
        if entity is None:
            continue
        is_implementation = entity.has_class(S.IMPLEMENTATION)
        is_attachment_or_collection = entity.has_class(S.ATTACHMENT) or entity.has_class(S.COLLECTION)
        offends = {
            S.ROLE_DESIGN: ("sbol2-12504", is_implementation),
            S.ROLE_BUILD: ("sbol2-12505", not is_implementation),
            S.ROLE_TEST: ("sbol2-12506", not is_attachment_or_collection),
            S.ROLE_LEARN: ("sbol2-12507", is_implementation),
        }
        for role in obj.iris(S.HAD_ROLE):
            if role in offends and offends[role][1]:
                ctx.warning(
                    offends[role][0], obj, "a Usage's entity should match the TopLevel kind its role expects", S.ENTITY
                )
