"""Provenance rules: generation cycles and the design-build-test-learn role conventions for Activities,
Associations, and Usages."""

from __future__ import annotations

from collections.abc import Callable

from sbol_utilities.validation.graphs import nodes_reaching_cycles
from sbol_utilities.validation.sbol2 import spec as S
from sbol_utilities.validation.sbol2.context import Sbol2Context, Sbol2Object
from sbol_utilities.validation.sbol2.registry import REGISTRY


def _generated_from(ctx: Sbol2Context, obj: Sbol2Object) -> list[str]:
    """The entities used by the Activities that generated ``obj``."""
    return [
        entity
        for activity in ctx.referenced(obj, S.WAS_GENERATED_BY)
        for usage in ctx.referenced(activity, S.QUALIFIED_USAGE)
        if (entity := usage.first_iri(S.ENTITY)) is not None
    ]


@REGISTRY.rule("sbol2-10223")
def generation_cycles(ctx: Sbol2Context) -> None:
    """wasGeneratedBy and the entities of the generating Activities' Usages do not form a cycle."""
    graph = {obj.iri: _generated_from(ctx, obj) for obj in ctx.objects if obj.iri is not None}
    offenders = nodes_reaching_cycles(graph, lambda node: graph.get(node, ()))
    for obj in ctx.objects:
        if obj.iri in offenders:
            ctx.report(
                "sbol2-10223",
                obj,
                "provenance formed by wasGeneratedBy and Usage entity references must not be circular",
                property=S.WAS_GENERATED_BY,
            )


#: (Association role of the generating Activity, rule, whether a generated object offends it, message)
_GENERATED_KINDS: tuple[tuple[str, str, Callable[[Sbol2Object], bool], str], ...] = (
    (
        S.ROLE_DESIGN,
        "sbol2-10224",
        lambda obj: obj.has_class(S.IMPLEMENTATION) or not obj.is_top_level,
        "an object generated by a design Activity SHOULD be a TopLevel other than Implementation",
    ),
    (
        S.ROLE_BUILD,
        "sbol2-10225",
        lambda obj: not obj.has_class(S.IMPLEMENTATION),
        "an object generated by a build Activity SHOULD be an Implementation",
    ),
    (
        S.ROLE_TEST,
        "sbol2-10226",
        lambda obj: not obj.has_class(S.EXPERIMENTAL_DATA),
        "an object generated by a test Activity SHOULD be ExperimentalData",
    ),
    (
        S.ROLE_LEARN,
        "sbol2-10227",
        lambda obj: obj.has_class(S.IMPLEMENTATION),
        "an object generated by a learn Activity SHOULD NOT be an Implementation",
    ),
)


@REGISTRY.rule(*(rule for _, rule, _, _ in _GENERATED_KINDS))
def generated_object_kinds(ctx: Sbol2Context) -> None:
    """An object generated by a design/build/test/learn Activity has the matching TopLevel kind."""
    for obj in ctx.sbol_objects:
        roles = {
            role
            for activity in ctx.referenced(obj, S.WAS_GENERATED_BY)
            for association in ctx.referenced(activity, S.QUALIFIED_ASSOCIATION)
            for role in association.iris(S.HAD_ROLE)
        }
        for role, rule, offends, message in _GENERATED_KINDS:
            if role in roles and offends(obj):
                ctx.report(rule, obj, message)


#: (Association role of an Activity, rule, Usage roles that conflict with it)
_ACTIVITY_CONFLICTS = (
    (S.ROLE_DESIGN, "sbol2-12408", (S.ROLE_BUILD, S.ROLE_TEST)),
    (S.ROLE_BUILD, "sbol2-12409", (S.ROLE_TEST, S.ROLE_LEARN)),
    (S.ROLE_TEST, "sbol2-12410", (S.ROLE_DESIGN, S.ROLE_LEARN)),
    (S.ROLE_LEARN, "sbol2-12411", (S.ROLE_DESIGN, S.ROLE_BUILD)),
)


@REGISTRY.rule(*(rule for _, rule, _ in _ACTIVITY_CONFLICTS))
def activity_usage_roles(ctx: Sbol2Context) -> None:
    """An Activity's Usage roles do not conflict with the role of its Association."""
    for obj in ctx.instances(S.ACTIVITY):
        association_roles = {r for a in ctx.referenced(obj, S.QUALIFIED_ASSOCIATION) for r in a.iris(S.HAD_ROLE)}
        usage_roles = {r for u in ctx.referenced(obj, S.QUALIFIED_USAGE) for r in u.iris(S.HAD_ROLE)}
        for association_role, rule, forbidden in _ACTIVITY_CONFLICTS:
            if association_role in association_roles and any(r in usage_roles for r in forbidden):
                ctx.report(
                    rule,
                    obj,
                    "an Activity's Usage roles should not conflict with its Association role",
                    property=S.QUALIFIED_USAGE,
                )


#: (Usage role, rule, whether the entity used offends it)
_USAGE_ENTITY_KINDS: tuple[tuple[str, str, Callable[[Sbol2Object], bool]], ...] = (
    (S.ROLE_DESIGN, "sbol2-12504", lambda entity: entity.has_class(S.IMPLEMENTATION)),
    (S.ROLE_BUILD, "sbol2-12505", lambda entity: not entity.has_class(S.IMPLEMENTATION)),
    (S.ROLE_TEST, "sbol2-12506", lambda entity: not entity.has_class(S.ATTACHMENT, S.COLLECTION)),
    (S.ROLE_LEARN, "sbol2-12507", lambda entity: entity.has_class(S.IMPLEMENTATION)),
)


@REGISTRY.rule(*(rule for _, rule, _ in _USAGE_ENTITY_KINDS))
def usage_entity_kinds(ctx: Sbol2Context) -> None:
    """A Usage with a design/build/test/learn role refers to an entity of the kind that role expects."""
    for obj in ctx.instances(S.USAGE):
        entity = ctx.resolve(obj.first_iri(S.ENTITY))
        if entity is None:
            continue
        roles = obj.iris(S.HAD_ROLE)
        for role, rule, offends in _USAGE_ENTITY_KINDS:
            if role in roles and offends(entity):
                ctx.report(
                    rule, obj, "a Usage's entity should match the TopLevel kind its role expects", property=S.ENTITY
                )
