"""Access to the sbol-rs validation goldens (test/test_files/sbol_rs_golden/validation.json).

The goldens are generated by ``tools/generate_sbol_rs_goldens.py``. Each file entry lists the distinct
``[rule, severity, subject, [config names]]`` issues sbol-rs reports for that file.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Dict, List, Set, Tuple

import sboltestsuite

from sbol_utilities.validation import ValidationConfig, ValidationReport

TEST_DIR = Path(__file__).resolve().parent
GOLDEN = TEST_DIR / "test_files" / "sbol_rs_golden" / "validation.json"
RULE_CASES = TEST_DIR / "validation_cases"

IssueKey = Tuple[str, str, str]


@lru_cache(maxsize=None)
def goldens() -> dict:
    """The parsed golden file."""
    return json.loads(GOLDEN.read_text(encoding="utf-8"))


def configs(version: str) -> Dict[str, ValidationConfig]:
    """Golden config name -> equivalent ValidationConfig, for ``sbol2`` or ``sbol3``."""
    return {name: ValidationConfig(**kwargs) for name, kwargs in goldens()["configs"][version].items()}


def expected(name: str, config: str) -> Set[IssueKey]:
    """(rule, severity, subject) issues sbol-rs reports for a golden file under a config."""
    entry = goldens()["files"][name]
    return {(rule, severity, subject) for rule, severity, subject, cfgs in entry["issues"] if config in cfgs}


def actual(report: ValidationReport) -> Set[IssueKey]:
    """(rule, severity, subject) issues of a Python report, normalized like the goldens."""
    result = set()
    for issue in report.issues:
        subject = issue.subject or ""
        if subject.startswith("_:"):
            subject = "_:"
        result.add((issue.rule, issue.severity, subject))
    return result


def is_parse_error(name: str) -> bool:
    """Whether sbol-rs rejected the file before validation."""
    return any(rule == "<parse-error>" for rule, *_ in goldens()["files"][name]["issues"])


def describe(missing: Set[IssueKey], extra: Set[IssueKey], limit: int = 25) -> str:
    """Readable summary of a golden mismatch."""
    lines: List[str] = []
    for label, items in (("missing (sbol-rs reports, Python does not)", missing), ("extra (Python only)", extra)):
        if items:
            lines.append(f"{label}: {len(items)}")
            lines.extend(f"  {rule} {severity} {subject}" for rule, severity, subject in sorted(items)[:limit])
    return "\n".join(lines)


def golden_path(name: str) -> Path:
    """Filesystem path of a golden file key."""
    if name.startswith("repo/"):
        return TEST_DIR / "test_files" / name[len("repo/") :]
    if name.startswith("cases/"):
        return RULE_CASES / name[len("cases/") :]
    return sboltestsuite.suite_root() / name
